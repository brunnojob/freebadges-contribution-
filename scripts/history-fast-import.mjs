import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawn} from 'node:child_process';
import {randomUUID} from 'node:crypto';
import {datesPlan} from '../docs/js/github.js';

function git(args,cwd,env,input) {
  return new Promise((resolve,reject)=>{
    const child=spawn('git',args,{cwd,env,stdio:['pipe','pipe','pipe']});
    let output='',error='';
    child.stdout.on('data',d=>output+=d);
    child.stderr.on('data',d=>error+=d);
    child.on('error',reject);
    child.on('close',code=>code===0?resolve(output.trim()):reject(new Error(`GIT_FAILED: ${error.slice(-400)}`)));
    child.stdin.on('error',reject);
    child.stdin.end(input);
  });
}

export async function publishHistory(repo,user,plan,token,{record=()=>{}}={}) {
  const dates=datesPlan(plan.start,plan.end,plan.daily);
  const dir=await mkdtemp(join(tmpdir(),'freebadges-history-'));
  const branch=`achievement-studio/history-${randomUUID()}`;
  const email=`${user.id}+${user.login}@users.noreply.github.com`;
  const remote=`https://github.com/${repo.full_name}.git`;
  const env={...process.env,GIT_TERMINAL_PROMPT:'0',GIT_CONFIG_COUNT:'1',GIT_CONFIG_KEY_0:'http.https://github.com/.extraheader',GIT_CONFIG_VALUE_0:`AUTHORIZATION: basic ${Buffer.from(`x-access-token:${token}`).toString('base64')}`};
  try {
    await git(['init','-q'],dir,env);
    await git(['fetch','--no-tags',remote,`refs/heads/${repo.default_branch}`],dir,env);
    const base=await git(['rev-parse','FETCH_HEAD'],dir,env);
    const blob=await git(['hash-object','-w','--stdin'],dir,env,'Synthetic contribution history generated by Achievement Studio.\n');
    const path=`.achievement-studio/history-${randomUUID()}.txt`;
    let stream='';
    for(let i=0;i<dates.length;i++) {
      const seconds=Math.floor(Date.parse(dates[i])/1000);
      stream+=`commit refs/heads/${branch}\nmark :${i+1}\nauthor ${user.login} <${email}> ${seconds} +0000\ncommitter ${user.login} <${email}> ${seconds} +0000\ndata ${Buffer.byteLength(`chore: synthetic contribution ${i+1}/${dates.length}`)}\nchore: synthetic contribution ${i+1}/${dates.length}\nfrom ${i?':'+i:base}\nM 100644 ${blob} ${path}\n\n`;
    }
    await git(['fast-import','--quiet'],dir,env,stream);
    const head=await git(['rev-parse',`refs/heads/${branch}`],dir,env);
    await git(['push',remote,`${head}:refs/heads/${branch}`],dir,env);
    record('history-branch',`https://github.com/${repo.full_name}/tree/${branch}`,{branch});
    // A normal push rejects a changed or protected default branch without force.
    await git(['push',remote,`${head}:refs/heads/${repo.default_branch}`],dir,env);
    record('history-published',`https://github.com/${repo.full_name}/commits/${encodeURIComponent(repo.default_branch)}`,{sha:head,total:dates.length});
  } finally {await rm(dir,{recursive:true,force:true});}
}
